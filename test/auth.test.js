// Testa os 6 pilares do login (auth.js) contra o Supabase de teste (PGlite + regras reais)
const Module = require('module'), path = require('path')
const orig = Module._resolveFilename
Module._resolveFilename = function (req, ...a) { return req === 'electron' ? path.join(__dirname, 'electron-stub.js') : orig.call(this, req, ...a) }
process.env.RETOMA_FAKE_CLOUD = path.join(__dirname, 'fake-supabase.js')
const Auth = require('../src/auth.js')
let fails = 0; const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) fails++ }
;(async () => {
  const E = 'ana@teste.com', P = 'senha123'
  // 2. validação
  ok((await Auth.signIn({ email: '', password: 'x' })).error === 'Digite seu e-mail.', 'campo vazio: pede o e-mail')
  ok((await Auth.signIn({ email: 'ana@', password: 'x' })).error === 'E-mail inválido.', 'e-mail inválido')
  ok((await Auth.signUp({ email: E, password: 'curta', name: 'Ana' })).code === 'validation', 'senha curta recusada')
  ok((await Auth.signUp({ email: E, password: 'somenteletras', name: 'Ana' })).error.includes('letras e números'), 'senha sem número recusada')
  ok((await Auth.signUp({ email: E, password: P, name: '' })).error === 'Digite seu nome.', 'nome obrigatório')
  // 1. cadastro e entrada
  const su = await Auth.signUp({ email: ' ANA@teste.com ', password: P, name: 'Ana' })
  ok(su.ok && su.user && su.user.email === E, 'cadastro (e-mail normalizado)')
  ok((await Auth.signUp({ email: E, password: P, name: 'Ana' })).code === 'user_already_exists', 'conta repetida: mensagem amigável')
  ok((await Auth.currentUser()).email === E, 'sessão ativa após cadastro')
  await Auth.signOut(); ok((await Auth.currentUser()) === null, 'saiu da conta')
  // 2. senha errada + bloqueio
  const w1 = await Auth.signIn({ email: E, password: 'errada1' })
  ok(w1.code === 'invalid_credentials' && w1.error.startsWith('E-mail ou senha incorretos'), 'senha errada: ' + w1.error)
  ok((await Auth.signIn({ email: 'ninguem@teste.com', password: 'x1' })).code === 'invalid_credentials', 'conta inexistente: mesma mensagem (não revela quem tem cadastro)')
  let last; for (let i = 0; i < 4; i++) last = await Auth.signIn({ email: E, password: 'errada' + i })
  ok(last.code === 'locked', 'bloqueio após 5 erros: ' + last.error)
  ok((await Auth.signIn({ email: E, password: P })).code === 'locked', 'bloqueado mesmo com a senha certa (2 min)')
  Auth._test.clearFails(E)
  const si = await Auth.signIn({ email: E, password: P })
  ok(si.ok && si.user.name === 'Ana', 'entrou com a senha certa')
  // 3. esqueci a senha
  ok((await Auth.requestPasswordReset(E)).ok, 'pedido de código de recuperação')
  ok((await Auth.requestPasswordReset('naoexiste@teste.com')).ok, 'mesma resposta pra e-mail sem conta')
  ok((await Auth.confirmPasswordReset({ email: E, code: '999999', password: 'novaSenha9' })).code === 'otp_invalid', 'código errado recusado')
  ok((await Auth.confirmPasswordReset({ email: E, code: '12', password: 'novaSenha9' })).code === 'validation', 'código incompleto recusado')
  ok((await Auth.confirmPasswordReset({ email: E, code: '123456', password: 'novaSenha9' })).ok, 'nova senha salva com o código')
  await Auth.signOut()
  ok(!(await Auth.signIn({ email: E, password: P })).ok && (await Auth.signIn({ email: E, password: 'novaSenha9' })).ok, 'senha antiga não entra, nova entra')
  // 5. verificação em 2 etapas
  const en = await Auth.mfaEnroll()
  ok(en.ok && en.qr.startsWith('data:image/svg+xml') && en.secret, 'ativação: QR code e chave')
  ok((await Auth.mfaActivate({ factorId: en.factorId, code: '000000' })).code === 'mfa_invalid', 'código do app errado recusado')
  ok((await Auth.mfaActivate({ factorId: en.factorId, code: '123456' })).ok, '2 etapas ativada')
  ok((await Auth.mfaStatus()).enabled, 'status: ativa')
  await Auth.signOut()
  const s2 = await Auth.signIn({ email: E, password: 'novaSenha9' })
  ok(s2.ok && s2.mfaRequired && s2.factorId, 'login pede o código de 2 etapas')
  ok((await Auth.currentUser()) === null, 'sem o código, não conta como logado')
  ok((await Auth.mfaVerifyLogin({ factorId: s2.factorId, code: 'abc' })).code === 'validation', 'código com letras recusado')
  const s3 = await Auth.mfaVerifyLogin({ factorId: s2.factorId, code: '123456' })
  ok(s3.ok && s3.user.email === E, 'entrou com o código')
  ok((await Auth.mfaDisable({ factorId: s2.factorId })).ok && !(await Auth.mfaStatus()).enabled, '2 etapas desativada')
  // 4. tempo limite
  const t = await Auth._test.withTimeout(new Promise(() => {}), 50).catch(e => Auth._test.friendly(e))
  ok(t.code === 'timeout' && t.error.includes('demorou'), 'servidor lento: ' + t.error)
  ok(Auth._test.friendly({ message: 'fetch failed' }).code === 'offline', 'sem internet: mensagem própria')
  ok(Auth._test.friendly({ status: 429, message: 'x' }).code === 'rate_limited', 'limite do servidor (429)')
  // 1. Google: abre o navegador do sistema
  // (o retorno real precisa do Supabase; aqui só confere que não trava e trata o erro)
  // 1.1 — convidado entra pelo código do e-mail e cria a senha
  ok((await Auth.requestEmailCode('sem-convite@teste.com')).code === 'no_invite', 'e-mail sem convite: "não encontramos convite"')
  ok((await Auth.sendInviteEmail('vend@teste.com')).ok, 'gerente dispara o e-mail de convite')
  ok((await Auth.requestEmailCode('vend@teste.com')).ok, 'convidado pede o código de novo')
  ok((await Auth.verifyEmailCode({ email: 'vend@teste.com', code: '000000' })).code === 'otp_invalid', 'código errado recusado')
  const iv = await Auth.verifyEmailCode({ email: 'vend@teste.com', code: '123456' })
  ok(iv.ok && iv.needsPassword, 'código certo: entrou e pede pra criar senha')
  ok((await Auth.finishProfile({ name: '', password: 'senha123' })).code === 'validation', 'nome obrigatório')
  ok((await Auth.finishProfile({ name: 'Vitor', password: 'curta' })).code === 'validation', 'senha fraca recusada')
  const fp = await Auth.finishProfile({ name: 'Vitor', password: 'senha123' })
  ok(fp.ok && fp.user.name === 'Vitor', 'senha e nome salvos')
  await Auth.signOut()
  const vi = await Auth.signIn({ email: 'vend@teste.com', password: 'senha123' })
  ok(vi.ok && vi.user.name === 'Vitor', 'próximos acessos: entra com e-mail e senha')
  const vv = await Auth.verifyEmailCode({ email: 'vend@teste.com', code: '123456' })
  ok(vv.ok && !vv.needsPassword, 'quem já tem senha não precisa criar de novo')
  await Auth.signOut(); await Auth.signIn({ email: E, password: 'novaSenha9' })
  // LGPD
  ok((await Auth.deleteAccount()).ok, 'excluir conta')
  ok((await Auth.signIn({ email: E, password: 'novaSenha9' })).code === 'invalid_credentials', 'conta excluída não entra mais')
  console.log(fails ? `\n${fails} FALHA(S)` : '\nTUDO OK')
  process.exit(fails ? 1 : 0)
})().catch(e => { console.log('ERRO', e.stack); process.exit(1) })
