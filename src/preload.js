const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('api', {
  getData:      ()       => ipcRenderer.invoke('get-data'),
  setData:      (data)   => ipcRenderer.invoke('set-data', data),
  openWhatsapp: (phone, biz) => ipcRenderer.send('open-whatsapp', { phone, biz }),
  notify:       (t, b)   => ipcRenderer.send('notify', { title: t, body: b }),
  minimize:     ()       => ipcRenderer.send('minimize'),
  updateBadge:  (n)      => ipcRenderer.send('update-badge', n),
  onReload:     (cb)     => ipcRenderer.on('reload-data', () => cb()),
  onShowOverdue:(cb)     => ipcRenderer.on('show-overdue', () => cb()),
  onEditItem:   (cb)     => ipcRenderer.on('edit-item', (_, id) => cb(id)),
  onShowDone:   (cb)     => ipcRenderer.on('show-done', () => cb()),
  complete:     (id)     => ipcRenderer.invoke('complete', id),
  restore:      (id)     => ipcRenderer.invoke('restore', id),
  getDone:      ()       => ipcRenderer.invoke('get-done'),
  setOutcome:   (id, o)  => ipcRenderer.invoke('set-outcome', { id, outcome: o }),
  getScore:     (biz)    => ipcRenderer.invoke('get-score', biz),
  reportPdf:    (o)      => ipcRenderer.invoke('report:pdf', o),
  getTemplates: ()       => ipcRenderer.invoke('get-templates'),
  setTemplates: (l)      => ipcRenderer.invoke('set-templates', l),
  openWhatsappText: (phone, text, biz) => ipcRenderer.send('open-whatsapp', { phone, text, biz }),
  // 0.7 — negócios e configurações
  getMeta:      ()       => ipcRenderer.invoke('get-meta'),
  setBusinesses:(l)      => ipcRenderer.invoke('set-businesses', l),
  setSettings:  (p)      => ipcRenderer.invoke('set-settings', p),
  setLastBiz:   (id)     => ipcRenderer.send('set-last-biz', id),
  setBizFilter: (id)     => ipcRenderer.send('set-biz-filter', id),
  onWppHint:    (cb)     => ipcRenderer.on('wpp-hint', (_, h) => cb(h)),
  onShowSettings:(cb)    => ipcRenderer.on('show-settings', () => cb()),
  // 1.0 — conta, sincronização, equipes, dados
  auth:         (ch, a)  => ipcRenderer.invoke('auth:' + ch, a),
  syncNow:      ()       => ipcRenderer.invoke('sync:now'),
  onSyncStatus: (cb)     => ipcRenderer.on('sync-status', (_, s) => cb(s)),
  team:         (ch, a)  => ipcRenderer.invoke('team:' + ch, a),
  exportData:   ()       => ipcRenderer.invoke('data:export'),
  wipeLocal:    ()       => ipcRenderer.invoke('data:wipe-local'),
  deleteForever:(id)     => ipcRenderer.invoke('delete-forever', id),
  setUi:        (p)      => ipcRenderer.send('set-ui', p),
  updateInstall:()       => ipcRenderer.invoke('update:install'),
  updateCheck:  ()       => ipcRenderer.invoke('update:check'),
  onUpdateState:(cb)     => ipcRenderer.on('update-state', (_, s) => cb(s)),
  openUrl:      (u)      => ipcRenderer.send('open-url', u),
  consumeUi:    (k)      => ipcRenderer.invoke('ui:consume', k),
  dragStart:  ()      => ipcRenderer.send('win-drag-start'),
  dragEnd:    ()      => ipcRenderer.send('win-drag-end'),
  winMin:     ()      => ipcRenderer.send('win-min'),
  winMax:     ()      => ipcRenderer.send('win-max'),
  winClose:   ()      => ipcRenderer.send('win-close'),
  onWinMax:   (cb)    => ipcRenderer.on('win-max', (_, v) => cb(v)),
})
